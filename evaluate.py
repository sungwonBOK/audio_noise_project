"""Tune thresholds on validation; report test performance using locked thresholds."""
import argparse
import csv
import time
from pathlib import Path

import numpy as np
import torch

from audio_utils import render_recipe, max_frame_dbfs
from common import device_for, load_checkpoint, read_json, read_manifest, sha256, synchronize, write_json
from metrics import scores, tune_thresholds
from model import SoundDetector


def predict_rows(model, rows, cfg, device, rms_db=None):
    probabilities = np.zeros((len(rows), 5), dtype=np.float32)
    skipped = np.zeros(len(rows), dtype=bool)
    timings = dict(audio_load_mix_seconds=0.0, rms_seconds=0.0, model_seconds=0.0,
                   model_windows=0, skipped_windows=0)
    synchronize(device)
    started = time.perf_counter()
    # Sequential windows match file inference. Timing is not batch throughput.
    for i, row in enumerate(rows):
        t = time.perf_counter()
        wave = render_recipe(row, cfg)
        timings["audio_load_mix_seconds"] += time.perf_counter() - t
        if rms_db is not None:
            t = time.perf_counter()
            level = max_frame_dbfs(wave, cfg["sample_rate"], cfg["rms_frame_seconds"], cfg["rms_hop_seconds"])
            skipped[i] = level < rms_db
            timings["rms_seconds"] += time.perf_counter() - t
        if skipped[i]:
            timings["skipped_windows"] += 1
            continue
        synchronize(device)
        t = time.perf_counter()
        with torch.inference_mode():
            x = torch.from_numpy(wave).unsqueeze(0).to(device)
            probabilities[i] = model(x).sigmoid()[0].cpu().numpy()
        synchronize(device)
        timings["model_seconds"] += time.perf_counter() - t
        timings["model_windows"] += 1
    synchronize(device)
    timings["pipeline_seconds"] = time.perf_counter() - started
    if not np.isfinite(probabilities).all():
        raise RuntimeError("Non-finite prediction")
    return probabilities, skipped, timings


def grouped_metrics(rows, y, probabilities, thresholds):
    result = {}
    def key_of(r):
        prefix = "long/" if r.get("source") == "long" else ""
        return f"{prefix}{r['kind']}/{r['noise_group']}/snr={r['snr_db']}"
    keys = sorted({key_of(r) for r in rows})
    for key in keys:
        idx = [i for i, r in enumerate(rows) if key_of(r) == key]
        result[key] = scores(y[idx], probabilities[idx], thresholds)
    for noise in sorted({r["noise_class"] for r in rows if r["noise_class"]}):
        idx = [i for i, r in enumerate(rows) if r["noise_class"] == noise]
        result[f"noise_class/{noise}"] = scores(y[idx], probabilities[idx], thresholds)
    return result


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--checkpoint", required=True)
    p.add_argument("--manifest", default="data/manifest.json")
    p.add_argument("--split", choices=["val", "test"], required=True)
    p.add_argument("--tune", action="store_true")
    p.add_argument("--thresholds", help="Required for test. Generated by --split val --tune")
    p.add_argument("--out", required=True)
    p.add_argument("--rms-db", type=float, default=None, help="Optional gate threshold in dBFS; choose using validation")
    p.add_argument("--device", default=None)
    a = p.parse_args()
    if a.tune and (a.split != "val" or a.rms_db is not None):
        p.error("Tune only on ungated validation. Evaluate RMS separately with the same thresholds.")
    if not a.tune and not a.thresholds:
        p.error("Specify --thresholds, or --split val --tune")
    checkpoint = load_checkpoint(a.checkpoint)
    cfg = checkpoint["config"]
    device = device_for(a.device or cfg["device"])
    m = read_manifest(a.manifest, cfg)
    manifest_hash = sha256(a.manifest)
    if manifest_hash != checkpoint["provenance"]["manifest_sha256"]:
        raise ValueError("Evaluation manifest differs from this model's recorded experiment")
    model_hash = sha256(a.checkpoint)
    if not a.tune:
        threshold_info = read_json(a.thresholds)
        if threshold_info["checkpoint_sha256"] != model_hash or threshold_info["classes"] != cfg["classes"]:
            raise ValueError("Thresholds belong to a different checkpoint/class order")
        thresholds = threshold_info["thresholds"]
    rows = [r for r in m["rows"] if r["split"] == a.split]
    if not rows or any(r.get("source") != "long" and sum(r["labels"]) > 1 for r in rows):
        raise ValueError("Empty split or overlapping target labels outside project scope")
    y = np.asarray([r["labels"] for r in rows], dtype=np.int32)
    model = SoundDetector()
    model.load_state_dict(checkpoint["model"])
    model.to(device).eval()
    # Warm-up excluded from timing, model initialization also excluded.
    with torch.inference_mode():
        model(torch.zeros(1, round(cfg["sample_rate"]*cfg["window_seconds"]), device=device))
    synchronize(device)
    probs, _, timing = predict_rows(model, rows, cfg, device)
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=False)
    if a.tune:
        thresholds = tune_thresholds(y, probs)
        write_json(out / "thresholds.json", {"classes": cfg["classes"], "thresholds": thresholds,
                   "checkpoint_sha256": model_hash, "manifest_sha256": manifest_hash,
                   "selection_split": "val", "objective": "per-class F1 on fixed grid 0.05:0.05:0.95"})
    report = {"split": a.split, "classes": cfg["classes"], "thresholds": thresholds,
              "checkpoint_sha256": model_hash, "manifest_sha256": manifest_hash,
              "unit": "5-second recipe windows (or configured window); not independent real-world events",
              "ungated": {"metrics": scores(y, probs, thresholds), "timing": timing,
                          "conditions": grouped_metrics(rows, y, probs, thresholds)},
              "timing_note": "Warm-up/model loading excluded. Model time includes transfer and sigmoid. Recipe time includes disk decode, resampling and synthesis. For real file wall time use infer.py; gated pass runs second and may benefit from cache."}
    gated = None
    skipped = np.zeros(len(rows), dtype=bool)
    if a.rms_db is not None:
        gated, skipped, gated_timing = predict_rows(model, rows, cfg, device, a.rms_db)
        base_pred, gate_pred = probs >= thresholds, gated >= thresholds
        report["gated"] = {"rms_dbfs": a.rms_db, "metrics": scores(y, gated, thresholds),
                           "timing": gated_timing, "conditions": grouped_metrics(rows, y, gated, thresholds),
                           "additional_missed_target_labels": int(((y == 1) & base_pred & ~gate_pred).sum()),
                           "positive_windows_skipped": int(((y == 1).any(1) & skipped).sum()),
                           "pipeline_speedup": timing["pipeline_seconds"] / max(gated_timing["pipeline_seconds"], 1e-9)}
    write_json(out / "report.json", report)
    with (out / "per_class.csv").open("w", newline="", encoding="utf-8-sig") as f:
        w = csv.writer(f)
        w.writerow(["class", "name_ko", "precision", "recall", "f1", "support", "threshold"])
        metric = report["ungated"]["metrics"]
        for i, c in enumerate(cfg["classes"]):
            w.writerow([c, cfg["class_names_ko"][i], metric["precision"][i], metric["recall"][i], metric["f1"][i], metric["support"][i], thresholds[i]])
    with (out / "predictions.csv").open("w", newline="", encoding="utf-8-sig") as f:
        w = csv.writer(f)
        w.writerow(["id", "kind", "noise_group", "noise_class", "snr_db", "labels", "scores", "gated_scores", "skipped"])
        for i, row in enumerate(rows):
            w.writerow([row["id"], row["kind"], row["noise_group"], row["noise_class"], row["snr_db"],
                        row["labels"], probs[i].tolist(), gated[i].tolist() if gated is not None else "", bool(skipped[i])])
    print(report["ungated"]["metrics"])
    print("Saved:", out)


if __name__ == "__main__":
    main()
